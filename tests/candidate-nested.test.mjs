import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtemp, mkdir, writeFile, rm, realpath, symlink } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { candidateFor } from "../src/runtime/lib/candidate.mjs";

test("explicit nested scope uses child Git inventory and detects deletions without ignored or sibling files", async t => {
  const root = await realpath(await mkdtemp(path.join(os.tmpdir(), "catpaw-nested-")));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = (cwd, ...args) => execFileSync("git", args, { cwd });
  git(root, "init", "-q");
  await mkdir(path.join(root, ".catpaw"));
  await writeFile(path.join(root, ".gitignore"), "child/\n");
  const child = path.join(root, "child");
  await mkdir(child);
  git(child, "init", "-q");
  await mkdir(path.join(child, "docs"));
  await writeFile(path.join(child, ".gitignore"), "docs/private.txt\n");
  const deliverable = path.join(child, "docs/guide.md");
  await writeFile(deliverable, "one");
  git(child, "add", "docs/guide.md");
  const options = { projectRoot: root };
  const work = { contract: 4, id: "FR-001", scope: "child/docs", owner: "primary", cycle: 1, acceptance: "docs", body: "" };
  const hash = () => candidateFor(options, work);
  const first = await hash();
  await writeFile(path.join(child, "docs/private.txt"), "ignored");
  await writeFile(path.join(root, "unrelated.txt"), "outside scope");
  assert.equal(await hash(), first);
  await writeFile(deliverable, "two");
  assert.notEqual(await hash(), first);
  await writeFile(deliverable, "one");
  await rm(deliverable);
  assert.notEqual(await hash(), first);
  await writeFile(deliverable, "one");
  assert.equal(await hash(), first);
  await writeFile(path.join(child, "docs/new.md"), "new");
  assert.notEqual(await hash(), first);
  await assert.rejects(candidateFor(options, { ...work, scope: "child/.git/config" }), /Git state/);
  await symlink(child, path.join(root, "alias"));
  await assert.rejects(candidateFor(options, { ...work, scope: "alias/docs" }), /unsafe link/);
});
